    + "\n\n"
    "이번 일은 **국정감사·자료분석 재료에서 사실 뽑기**다. 초안은 쓰지 않는다.\n"
    "\n"
    "찾을 종류 (자료에 있는 것만. 아래 아홉 개 밖의 종류는 만들지 않는다):\n"
