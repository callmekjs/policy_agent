"""국정감사형 Agent 둘의 지시문.

공통 한 문단만 주면 AI는 **무엇을 뽑아야 하는지 모른다.** 기존 본회의형에서
실제로 그랬다 — 발의안 전문을 주고도 사실 3건만 돌려주었다(6일차 기록).
그래서 Agent마다 따로 쓴다.

여기 적는 것은 **부탁이지 강제가 아니다.** 강제는 `extraction.verify_facts`와
`gate.check_draft`가 한다. 지시문은 "무엇을 찾아 달라"까지만 말하고,
"이 값을 써도 된다"는 판단은 절대 맡기지 않는다.
"""

