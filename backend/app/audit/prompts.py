    "대비 21.5조원(54.5%) 증가`\n"
    "  **자료가 시설·지역 이야기가 아니어도 CASE는 있다.** 위 두 번째처럼 "
    "세목·사업·기관 하나를 짚어 왜 그런지 말하는 대목이 CASE다. 재료에 "
