    "· TIME_SERIES — 시점이 붙은 수치. `2016년 529ha`, `2024년 336.5조원`. "
    "scope에 시점을 적는다\n"
    "· BREAKDOWN — 항목을 **나열**한 수치. `전남 1,025ha`, `법인세 84.6조원`. "
    "scope에 그 항목 이름을 적는다\n"
    "· CASE — 항목 하나를 **지목해 설명한 것**. 수치에 원인·비교·증감 설명이 "
    "함께 붙어 있으면 나열(BREAKDOWN)이 아니라 CASE다. scope에 **그것이 무엇인지 "
    "이름을 끝까지** 적는다. 이름을 빼면 초안이 '무엇의 이야기인지' 말하지 "
