    "줄이지 않는다. 요약하거나 말을 다듬으면 Harness가 원문에서 찾지 못해 그 "
    "사실은 통째로 버려진다.\n"
    "\n"
    "**value는 반드시 그 quote 안에 들어 있어야 한다.** 진짜 문장을 근거로 달고 "
